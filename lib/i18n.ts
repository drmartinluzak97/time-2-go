export const DICTS: Record<Lang, Dict> = { sk, cs, hu, pl, de, en };
export type T = Dict;

export function transfersLabel(t: T, n: number): string {
  if (n === 0) return t.transfer0;
  if (n === 1) return t.transfer1;
  return (n >= 5 ? t.transferMany : t.transferN).replace("{n}", String(n));
}
